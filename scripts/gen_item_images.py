def _art_exists(key: str) -> bool:
    """Есть ли уже картинка. Расширение перебираем: после optimize_images.py
    арты лежат в JPEG, и проверка только по .png гнала бы всё на перегенерацию."""
    return any(os.path.exists(os.path.join(OUT_DIR, key + e))
               for e in (".png", ".jpg", ".jpeg", ".webp"))


def base_prompt(base: str) -> str:
    """Промпт для базовой картинки семейства процедурной экипировки."""
    subject, paired = _BASE_ART[base]
    # Для парных вещей общий запрет «ровно один предмет» надо снять: перчатки
    # и сапоги в единственном экземпляре выглядят как потеря половины комплекта.
    con = ITEM_CONSTRAINTS
    if paired:
        con = con.replace("Ровно один предмет в кадре, целиком, "
                          "без вторых экземпляров, без коллажа и без сетки вариантов",
                          "Ровно одна пара — два одинаковых зеркальных предмета "
                          "рядом, целиком, без коллажа и без сетки вариантов")
    style = STYLE
    if paired:
        style = style.replace("один предмет строго по центру",
                              "пара предметов строго по центру")
    # Материал задаём отдельной фразой, иначе модель тянет броню к парадному
    # золоту. Для лёгкой брони сталь противопоказана: это ткань и мягкая кожа.
    material = ("Материал — грубое сукно, полотно и мягкая кожа, "
                "без металла, без позолоты и без драгоценных камней"
                if base.startswith("g_light") else
                "Материал — тёмная вороненая сталь, кожа и дерево, "
                "без позолоты и без драгоценных камней сверх описанного")
    return f"{con}. {subject}. {material}. {style}"


def pick_items(args):
    # Точечная перегенерация: --ids ключ1,ключ2 (остальные фильтры игнорируются,
    # чтобы можно было переделать конкретный предмет любого типа).
    want = {s.strip() for s in (getattr(args, "ids", "") or "").split(",") if s.strip()}
    if want:
        known = set(ITEMS) | set(_BASE_ART)
        missing = [k for k in want if k not in known]
        if missing:
            print(f"  ! нет таких предметов: {', '.join(missing)}")
        return sorted(k for k in want if k in known and "#" not in k)
    # --bases: 23 базовые картинки на всю процедурную экипировку вместо 161.
    if getattr(args, "bases", False):
        keys = sorted(_BASE_ART)
        if args.only_missing:
            keys = [k for k in keys if not _art_exists(k)]
        return keys[:args.limit] if args.limit else keys
    keys = []
    for k, v in ITEMS.items():
        if "#" in k:                      # пропустить динамические редкости
            continue
        if not args.include_gen and k.startswith("g_"):
            continue
        t = v.get("type")
        if args.type and t != args.type:
            continue
        if not args.type and t not in ("weapon", "armor", "accessory", "consumable", "rune"):
            continue
        keys.append(k)
    keys.sort()
    if args.only_missing:
        keys = [k for k in keys if not _art_exists(k)]
    if args.limit:
        keys = keys[:args.limit]
    return keys


def comfy_post(host: str, path: str, payload: dict) -> dict:
    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(f"http://{host}{path}", data=data,
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read())


def comfy_get(host: str, path: str) -> bytes:
    with urllib.request.urlopen(f"http://{host}{path}", timeout=60) as r:
        return r.read()


def generate_one(host: str, base_wf: dict, key: str, size: int, seed: int = 0) -> bool:
    wf = json.loads(json.dumps(base_wf))             # копия
    wf["7"]["inputs"]["text"] = build_prompt(key)    # промпт
    # seed=0 → случайный (повторный запуск даёт другой вариант того же промпта);
    # заданный seed → воспроизводимость для честного сравнения формулировок.
    wf["11"]["inputs"]["noise_seed"] = int(seed) if seed else random.randint(1, 2**50)
    wf["8"]["inputs"]["width"] = size
    wf["8"]["inputs"]["height"] = size
    wf["15"]["inputs"]["filename_prefix"] = f"item_{key}"
    resp = comfy_post(host, "/prompt", {"prompt": wf})
    pid = resp.get("prompt_id")
    if not pid:
        print(f"  ! {key}: нет prompt_id ({resp})"); return False
    # ждать готовности
    for _ in range(180):                              # до ~3 мин на картинку
        time.sleep(1)
        try:
            hist = json.loads(comfy_get(host, f"/history/{pid}"))
        except Exception:
            continue
        if pid in hist:
            outs = hist[pid].get("outputs", {}).get("15", {}).get("images", [])
            if not outs:
                print(f"  ! {key}: нет выходных изображений"); return False
            img = outs[0]
            q = urllib.parse.urlencode({"filename": img["filename"],
                                        "subfolder": img.get("subfolder", ""),
                                        "type": img.get("type", "output")})
            data = comfy_get(host, f"/view?{q}")
            os.makedirs(OUT_DIR, exist_ok=True)
            with open(os.path.join(OUT_DIR, key + ".png"), "wb") as f:
                f.write(data)
            return True
    print(f"  ! {key}: таймаут ожидания"); return False


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--host", default="127.0.0.1:8188")
    ap.add_argument("--type", choices=list(TYPE_RU))
    ap.add_argument("--only-missing", action="store_true")
    ap.add_argument("--include-gen", action="store_true")
    ap.add_argument("--bases", action="store_true",
                    help="23 базовые картинки процедурной экипировки "
                         "(одна на все тиры семейства g_axe_1…g_axe_90)")
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--size", type=int, default=1024)
    ap.add_argument("--ids", default="",
                    help="точечно: ключи предметов через запятую (напр. стальной_меч)")
    ap.add_argument("--seed", type=int, default=0,
                    help="фиксированный сид (честно сравнивать формулировки промпта)")
    ap.add_argument("--dry-run", action="store_true",
                    help="только показать промпты, НЕ генерировать")
    args = ap.parse_args()

    if args.dry_run:
        for _k in pick_items(args):
            print(f"\n=== {_k} ===\n{build_prompt(_k)}")
        print(f"\n({len(pick_items(args))} шт. — генерация не запускалась)")
        return

    if not os.path.exists(WORKFLOW):
        print("Не найден workflow_final.json в корне проекта."); return
    base_wf = json.load(open(WORKFLOW, encoding="utf-8"))
    keys = pick_items(args)
    print(f"К генерации: {len(keys)} предметов через ComfyUI @ {args.host}")
    ok = fail = 0
    for i, key in enumerate(keys, 1):
        label = (ITEMS[key].get("name", key) if key in ITEMS
                 else "база семейства: " + _BASE_ART[key][0].split(",")[0])
        print(f"[{i}/{len(keys)}] {key} — {label}")
        try:
            if generate_one(args.host, base_wf, key, args.size, seed=args.seed):
                ok += 1
            else:
                fail += 1
        except Exception as e:
            fail += 1
            print(f"  ! {key}: ошибка {e}")
    print(f"\nГотово: ✅ {ok}, ❌ {fail}. Картинки в images/items/.")
    print("Бот сам наложит цветную рамку редкости при показе.")


if __name__ == "__main__":
    main()
