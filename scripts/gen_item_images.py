def _visual_desc(desc) -> str:
    """Оставить в промпте только ВИЗУАЛЬНУЮ часть описания предмета.

    Причина (плейтест владельца: «много предметов с надписями»): поле desc в
    items.yaml — это игровая механика, а не внешний вид: «Восстанавливает 35 HP»,
    «+14 атаки, +2 Силы». Отдавая её в промпт, мы прямым текстом просим модель
    нарисовать цифры и аббревиатуры — она честно рисует их на этикетках и
    клинках. Поэтому режем предложения с цифрами, плюсами и игровыми терминами;
    если визуального остатка нет — описание вовсе не идёт в промпт (образ
    строится по типу и названию предмета)."""
    import re
    raw = " ".join((desc or "").replace("\n", " ").split())
    if not raw:
        return ""
    _MECH = ("hp", "мана", "маны", "атаки", "атака", "защит", "силы", "ловк",
             "инт", "дух", "крит", "урон", "восстанавлив", "уровень", "ур.",
             "шанс", "сек", "бонус", "прочност")
    keep = []
    for sent in re.split(r"[.;]", raw):
        s = sent.strip()
        if not s:
            continue
        low = s.lower()
        if any(ch.isdigit() for ch in s) or "+" in s or "%" in s:
            continue                       # цифры/проценты → модель рисует их
        if any(w in low for w in _MECH):
            continue                       # игровые термины — не внешний вид
        keep.append(s)
    return keep[0] if keep else ""


