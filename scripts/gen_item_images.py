def _deglyph(text: str) -> str:
    """Убрать из текста слова, провоцирующие псевдо-письменность на предмете.

    Прилагательные («рунный топор») не заменяем на месте — получилась бы каша
    вида «с чеканным узором ... топор». Вместо этого слово-магнит вырезается,
    а пояснение переносится В КОНЕЦ фразы: «топор, с чеканным узором…»."""
    import re
    out = text or ""
    tail = []
    for bad, good in _NO_GLYPH:
        # вырезаем СЛОВО ЦЕЛИКОМ по корню: «клеймёный» → пусто, а не «ый»
        pat = re.compile(r"\S*" + re.escape(bad) + r"\S*", re.IGNORECASE)
        if pat.search(out):
            out = pat.sub("", out)
            if good not in tail:
                tail.append(good)
    out = " ".join(out.split())               # схлопнуть дыры от вырезанных слов
    out = out.replace(" ,", ",").strip(" ,")
    if tail:
        out = f"{out}, {', '.join(tail)}" if out else ", ".join(tail)
    return out

