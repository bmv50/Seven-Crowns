def _consum_art(key: str, name: str) -> str:
    hit = _CONSUM_ART.get(key)
    if hit:
        return f"{hit[0]}, {hit[1]}"
    low = (name or key).lower()
    if any(w in low for w in _HP_WORDS):
        color = "внутри ярко-алая жидкость с тёплым красным свечением"
    elif any(w in low for w in _MP_WORDS):
        color = "внутри лазурно-синяя жидкость с холодным синим свечением"
    else:
        color = "внутри золотисто-янтарная жидкость (не красная и не синяя)"
    return f"стеклянная склянка с пробкой, {color}"


def build_prompt(key: str) -> str:
    _ov = (_ITEM_OVERRIDES.get(key) or "").strip()
    if _ov:
        return _ov if "концепт-арт" in _ov else f"{ITEM_CONSTRAINTS}. {_ov}. {STYLE}"
    if key in _BASE_ART:                 # база семейства, а не предмет из items.yaml
        return base_prompt(key)
    meta = ITEMS.get(key, {})
    name = meta.get("name", key)
    if meta.get("type") == "rune":
        return _rune_prompt(key, name)
    kind = TYPE_RU.get(meta.get("type"), "фэнтезийный предмет")
    desc = _visual_desc(meta.get("desc"))
    # Имя — строчными и ПОСЛЕ типа предмета: имя с заглавной в начале промпта
    # модель принимает за надпись и рисует её на картинке (плейтест владельца).
    # Плюс обезвреживаем «рунный/клеймо/символ» → декоративные эквиваленты.
    subject = _deglyph(f"{kind}, {(name or '').lower()}")
    desc = _deglyph(desc)
    # Зелья/расходники — отдельный случай сразу по двум причинам.
    # 1) Стеклянный пузырёк модель почти всегда снабжает бумажной этикеткой.
    # 2) Имя вроде «малое зелье лечения» тянет за собой красный крест и подпись,
    #    а описание расходника — чистая механика («Восстанавливает 35 HP»).
    # Поэтому для них кадр целиком задаёт таблица _CONSUM_ART: форма сосуда и
    # цвет содержимого, а имя и описание в промпт не попадают вовсе.
    extra = ""
    if meta.get("type") == "consumable":
        subject = _consum_art(key, name)
        desc = ""
        # Фраза про стекло уместна только там, где стекло есть: приписывать её
        # миске с жаркое или свитку — сбивать модель лишним словом «стекло».
        if any(w in subject for w in ("стекл", "склянк", "колб", "бутыл",
                                      "флакон", "ампул", "хрустал")):
            extra = (" Гладкое стекло без этикеток, наклеек, бумажных ярлыков и "
                     "бирок, пробка или сургуч без клейма.")
        extra += (" Без крестов, символов и любых опознавательных знаков "
                  "на предмете.")
    parts = [ITEM_CONSTRAINTS, subject]
    if desc:
        parts.append(desc)
    tail = ". ".join(parts) + "."
    return f"{tail}{extra} {STYLE}"


