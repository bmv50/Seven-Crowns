# -*- coding: utf-8 -*-
"""
Ошибки атомарного жизненного цикла персонажа (Аудит-2а.1).

Живут в отдельном модуле без зависимостей, чтобы их могли импортировать И слой
БД (engine/db.py), И чистый флашер персистентности (engine/persist.py) без риска
циклического импорта. bot/main.py ловит их и превращает в честные сообщения игроку.
"""


class CharacterLifecycleError(Exception):
    """Базовый класс всех ошибок жизненного цикла персонажа."""


class ActiveCharacterExists(CharacterLifecycleError):
    """Попытка создать/восстановить героя, когда активная строка уже есть."""


class StaleCharacterWrite(CharacterLifecycleError):
    """Запись объекта устаревшего поколения: персонаж был сброшен/поднят в новом
    поколении, а в памяти остался старый объект. Писать его нельзя — иначе
    затрём нового/восстановленного героя. НЕ возвращается в очередь dirty."""


class CharacterNotFound(CharacterLifecycleError):
    """Операция над несуществующей строкой персонажа."""


class RestoreExpired(CharacterLifecycleError):
    """Окно восстановления (24 ч) после мягкого удаления истекло."""


class NameTaken(CharacterLifecycleError):
    """Имя уже занято активным персонажем (Аудит-2б.1). Поднимается при
    конкурентном создании двух героев с одинаковым именем: частичный уникальный
    индекс characters(name_norm) WHERE deleted_at IS NULL даёт UniqueViolationError,
    который create_character превращает в это исключение. bot/main.py ловит его и
    просит игрока выбрать другое имя (состояние создания сохраняется для повтора)."""
